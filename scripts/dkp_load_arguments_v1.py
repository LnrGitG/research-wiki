def meeting_id(date: str):
    """decision_id по дате заседания (FK argument -> decision)."""
    rows = query("SELECT d.decision_id FROM dkp.decision d "
                 "JOIN dkp.meeting m USING (meeting_id) WHERE m.meeting_date=%s",
                 (date,))
    return rows[0][0] if rows else None


def main() -> None:
    if query("SELECT count(*) FROM dkp.argument")[0][0] > 0:
        print("SKIP: argument уже заполнена")
        return
    n = 0
    for date, block, direction, text, span in ARGS:
        mid = meeting_id(date)
        if not mid:
            print("NO meeting", date)
            continue
        execute(
            "INSERT INTO dkp.argument (decision_id, block, direction, text_raw, source_span, classifier_version) "
            "VALUES (%s, %s, %s, %s, %s, 'manual_v1')",
            (mid, block, direction, text, span))
        n += 1
    print("inserted args:", n)
    print("total:", query("SELECT count(*) FROM dkp.argument")[0][0])
    print("== blocks by decision ==")
    for r in query("""SELECT m.meeting_date, a.block, a.direction, count(*)
                      FROM dkp.argument a JOIN dkp.meeting m USING (meeting_id)
                      GROUP BY 1,2,3 ORDER BY 1,2"""):
        print("  ", r)



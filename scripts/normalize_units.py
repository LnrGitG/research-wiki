#!/usr/bin/env python3
"""
Нормализация описательных единиц из разрезов в краткие обозначения.

В `sub_dimension` единица записана так, как она напечатана в публикации
Росстата: «В фактически действовавших ценах, миллионов рублей», «На конец
года, в процентах к среднероссийской стоимости», «Тысяч квадратных метров
общей площади жилых помещений». Для интерфейса нужна краткая форма, а
исходная фраза сохраняется отдельным полем `uu` (unit_verbose).

Запуск:  python3 scripts/normalize_units.py   (тест)
         из build_metrics_catalog.py вызывается normalize_unit()
"""
import re

# Порядок важен: сначала более специфичные шаблоны.
RULES = [
    (re.compile(r"тыс(яч)?\.?\s*(кв\.?\s*)?м²|тыс(яч)?\s+квадратных\s+метров", re.I), "тыс. м²"),
    (re.compile(r"кв\.?\s*м²|квадратных\s+метров", re.I), "м²"),
    (re.compile(r"млн\.?\s*м²|миллионов\s+квадратных\s+метров", re.I), "млн м²"),
    (re.compile(r"руб\.?/?\s*м²|рублей\s+за\s+кв", re.I), "руб./м²"),
    (re.compile(r"тыс\.?\s*руб|тысяч\s+рублей", re.I), "тыс. руб."),
    (re.compile(r"млрд\.?\s*руб|миллиард\w*\s+рублей", re.I), "млрд руб."),
    (re.compile(r"млн\.?\s*руб|миллион\w*\s+рублей", re.I), "млн руб."),
    (re.compile(r"^\s*руб|рублей\s*$", re.I), "руб."),
    (re.compile(r"процент|%\s*$|в\s+%", re.I), "%"),
    (re.compile(r"тыс\.?\s*чел|тысяч\s+человек", re.I), "тыс. чел."),
    (re.compile(r"чел(овек)?\b|лиц\b", re.I), "чел."),
    (re.compile(r"тыс\.?\s*шт|тысяч\s+(единиц|штук)", re.I), "тыс. ед."),
    (re.compile(r"единиц|штук|\bшт\b", re.I), "ед."),
    (re.compile(r"коэффициент|раз\b", re.I), "коэф."),
    (re.compile(r"индекс", re.I), "индекс"),
    # ВНИМАНИЕ: правила для «лет» и «месяцев» намеренно отсутствуют.
    # Фразы вида «На конец года» — не единица измерения, а указание на момент
    # наблюдения; автоматическое сведение их к «лет» давало ложные значения.
    # Если единица не распознана, возвращается None и остаётся значение
    # из справочника core.metric.
]


def normalize_unit(text):
    """Возвращает краткую единицу либо None, если распознать не удалось."""
    if not text:
        return None
    s = str(text).strip()
    if not s:
        return None
    # уже краткая форма — отдаём как есть
    if len(s) <= 14 and re.fullmatch(r"[%\wа-яёА-ЯЁ\.\s/²]+", s):
        if re.search(r"^(%|шт\.|ед\.|м²|руб\.|млн руб\.|тыс\. м²|тыс\. руб\.|"
                     r"млрд руб\.|чел\.|тыс\. чел\.|индекс|коэф\.|мес\.|лет)$", s):
            return s
    for rx, short in RULES:
        if rx.search(s):
            return short
    # очень длинное описание без явной единицы — не выдумываем
    if len(s) > 40:
        return None
    return s


if __name__ == "__main__":
    tests = [
        "В процентах от общего объема инвестиций в основной капитал",
        "На конец года, в процентах к среднероссийской стоимости",
        "В фактически действовавших ценах, миллионов рублей",
        "Тысяч квадратных метров общей площади жилых помещений",
        "Квадратных метров общей площади жилых помещений",
        "На конец года",
        "руб./м²", "%", "шт.",
        "Тысяч человек",
        "единиц",
    ]
    for t in tests:
        print("  %-58s -> %s" % (t[:58], normalize_unit(t)))

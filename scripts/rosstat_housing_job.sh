#!/bin/bash

# --- журнал загрузок (ops.ingest_run), см. scripts/run_logged.py ---
if [ -z "${INGEST_LOGGED:-}" ]; then
  exec env INGEST_LOGGED=1 /home/lnr/.hermes/hermes-agent/venv/bin/python3 \
       /home/lnr/research-wiki-private/scripts/run_logged.py --job "$(basename "$0")" -- bash "$0" "$@"
fi

# rosstat_housing_job.sh — cron-обёртка: ввод в действие зданий (Росстат), прямой контур.
#
# 1) rosstat_vv_zd_files_update.py — докачка файлов с портала Росстата:
#    vv-zd-sub_MM-YYYY.xlsx (по субъектам РФ, кумулятивный внутри года: в
#    сентябрьском выпуске лежат январь..сентябрь) и vv-zd-oper_Qkv-YYYY.xlsx
#    (по типам зданий в РФ, накопленным итогом с начала года). Попутно
#    подтягиваются vv-mosh-oper / vv-mosh-sub — они нужны следующей группе
#    (ввод производственных мощностей).
# 2) APPLY=1 PRUNE=period direct_vv_zd.py — ввод зданий в канон: 12 метрик по
#    субъектам (жилые и нежилые / жилые / нежилые × количество и общая площадь
#    × месяц и накопительно с начала года) плюс 24 прежние метрики по типам
#    зданий в РФ (`rosstat_c1_*`), которые раньше читались из лендинга
#    `rosreestr_deals.db` и теперь берутся из того же файла напрямую.
#    Режим PRUNE=period обязателен: файл кумулятивный и ревизуемый (Росстат
#    уточняет закрытые месяцы), а строка ввода зданий — скользящее окно года.
#    Территория без ввода в месяце в файле просто ОТСУТСТВУЕТ, поэтому дыра
#    «регион — месяц» в каноне означает отчётность источника, а не потерю при
#    разборе.
# 3) APPLY=1 PRUNE=period direct_mosh.py — ввод производственных мощностей по
#    видам деятельности (`vv-mosh-oper`), накопленным итогом с начала года,
#    частота Q. Метрика называется продуктом, а не строкой-разделом книги:
#    16.10.2026 прежний путь ошибался здесь на строку, под именем вида
#    деятельности («Деятельность ветеринарная») стояли числа конкретного
#    продукта («Ветеринарный пункт»). По решению владельца ярлык исправлен,
#    84 метрики-раздела сняты (точка возврата —
#    `attic/mosh_sections_before.csv.gz`), а в подразрез пишется реальная
#    единица измерения («ед.: Тысяча мест»), которую прежний путь терял.
#    Разовая правка сделана 16.10.2026; в месячном прогоне RETIRE не нужен.
# 4) APPLY=1 PRUNE=period direct_mosh_sub.py — тот же показатель по субъектам
#    (`vv-mosh-sub`), 8 525 наблюдений на 85 регионах и 8 федеральных округах,
#    отдельным релизом `vv-mosh-sub_2kv-2026`, чтобы ряд не задвоился под двумя
#    релизами. Строка «Российская Федерация» в этом файле ПРОПУСКАЕТСЯ (её числа
#    уже пришли из vv-mosh-oper) и служит сверкой разбора: расхождение означает,
#    что один из двух файлов прочитан не по тому блоку.
#
# Все шаги идемпотентны: повторный прогон не плодит строк и не теряет периоды.
set -u
PY=/home/lnr/.hermes/hermes-agent/venv/bin/python3
REPO=/home/lnr/research-wiki-private
cd "$REPO" || exit 1

"$PY" scripts/rosstat_vv_zd_files_update.py \
  || echo "предупреждение: докачка файлов ввода зданий завершилась с ошибкой"

APPLY=1 PRUNE=period "$PY" scripts/direct_vv_zd.py || exit 2

APPLY=1 PRUNE=period "$PY" scripts/direct_mosh.py || exit 3

APPLY=1 PRUNE=period "$PY" scripts/direct_mosh_sub.py || exit 4

echo "rosstat_housing: ввод зданий (субъекты и типы), ввод мощностей (РФ и субъекты) загружены в канон"

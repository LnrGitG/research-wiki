#!/usr/bin/env bash
# Cron-обёртка группы ИКВ по регионам (инвестиции в основной капитал).
#
# 1) rosstat_inv_files_update.py — докачка `Inv_reg_kv_2020-<год>.xlsx`
#    (диапазон лет в имени Росстат сдвигает раз в год; проверка HTTP 200,
#    размера и сигнатуры zip).
# 2) APPLY=1 PRUNE=period direct_ikv_reg.py — разбор книги и запись в канон.
#    Режим PRUNE=period обязателен: книга выходит накопленным итогом, закрытые
#    кварталы Росстат уточняет.
#    ВАЖНО: ряд накопительный (подписи «I квартал», «I полугодие»,
#    «январь-сентябрь», «год»), поэтому метка накопления пишется в подразрез;
#    значения — как в источнике (решение владельца 16.10.2026).
#    Загрузчик пишет каждую метрику в тот релиз, где она уже лежит: объединение
#    трёх прежних релизов и снятие карточки-дубля `iokmrrkri` ждут решения
#    владельца (предложение — в queries/direct-loaders-plan.md, транш 5).
#
# Шаги идемпотентны: повторный прогон не плодит строк и не теряет периоды.
set -u
PY=/home/lnr/.hermes/hermes-agent/venv/bin/python3
REPO=/home/lnr/research-wiki-private
cd "$REPO" || exit 9

"$PY" scripts/rosstat_inv_files_update.py || exit 1

APPLY=1 PRUNE=period "$PY" scripts/direct_ikv_reg.py || exit 2

echo "rosstat_invest: ИКВ по регионам (уровень и %) загружены в канон"

#!/usr/bin/env bash
# Cron-обёртка группы «парк строительной техники» (сборник «Строительство в России»).
#
# 1) rosstat_stroit_pril_files_update.py — докачка и распаковка приложения к
#    сборнику (`Srtoit_<год>.rar` → `yearbooks/Stroit_Pril_<год>/`).
# 2) APPLY=1 PRUNE=period direct_stroit_pril.py — разбор таблицы 2.11
#    («Наличие и состав парка основных строительных машин», на конец года):
#    по каждому виду машин две колонки — «всего, шт.» (`pste`) и «из них с
#    истёкшим сроком службы, %» (`dtiss`).
#
# Сборник выходит раз в год, поэтому прогон в основном проверочный: пока нового
# архива нет, шаги ничего не меняют (загрузчик пишет те же 1 379 строк, канон
# не растёт).
#
# Новые годы попадут в канон автоматически: загрузчик читает все распакованные
# приложения, год берётся из таблицы FILES — при появлении сборника за новый год
# в неё нужно добавить строку (путь, релиз, год). Это единственное ручное место.
set -u
PY=/home/lnr/.hermes/hermes-agent/venv/bin/python3
REPO=/home/lnr/research-wiki-private
cd "$REPO" || exit 9

"$PY" scripts/rosstat_stroit_pril_files_update.py || exit 1

APPLY=1 PRUNE=period "$PY" scripts/direct_stroit_pril.py || exit 2

echo "rosstat_stroit_pril: парк строительной техники по субъектам загружен в канон"
